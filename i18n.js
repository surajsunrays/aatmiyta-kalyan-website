let currentLanguage = "en";
const languageButton = document.querySelector("#language-toggle");
const textEntries = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
  acceptNode(node) {
    return node.parentElement.closest(
      "script,style,#language-toggle,#all-events,#dialog-label,#dialog-title,#dialog-description",
    )
      ? NodeFilter.FILTER_REJECT
      : NodeFilter.FILTER_ACCEPT;
  },
});
while (walker.nextNode()) {
  const node = walker.currentNode;
  const key = node.textContent.trim().replace(/\s+/g, " ");
  if (Object.hasOwn(marathi, key))
    textEntries.push({
      node,
      english: node.textContent,
      translated: node.textContent.replace(/\S[\s\S]*\S|\S/, marathi[key]),
    });
}
const accessibleEntries = [...document.querySelectorAll("[aria-label]")]
  .filter((el) => el !== languageButton && !el.matches(".menu-toggle"))
  .map((el) => ({ el, english: el.getAttribute("aria-label") }));
const englishTitle = document.title;
const description = document.querySelector('meta[name="description"]');
const englishDescription = description.content;
function translate(text) {
  return currentLanguage === "mr" ? (marathi[text] ?? text) : text;
}
function updateMenuLabel() {
  document
    .querySelector(".menu-toggle")
    .setAttribute(
      "aria-label",
      translate(
        document.querySelector(".menu-toggle").getAttribute("aria-expanded") ===
          "true"
          ? "Close navigation"
          : "Open navigation",
      ),
    );
}
function updateEventsLabel() {
  const button = document.querySelector("#all-events");
  if (!button) return;
  const expanded = button.getAttribute("aria-expanded") === "true";
  button.replaceChildren(
    document.createTextNode(
      translate(
        expanded ? "Show fewer celebrations" : "View all celebrations",
      ) + " ",
    ),
  );
  const icon = document.createElement("span");
  icon.textContent = expanded ? "−" : "＋";
  button.append(icon);
}
function setLanguage(language) {
  currentLanguage = language === "mr" ? "mr" : "en";
  document.documentElement.lang = currentLanguage;
  textEntries.forEach(({ node, english, translated }) => {
    node.textContent = currentLanguage === "mr" ? translated : english;
  });
  accessibleEntries.forEach(({ el, english }) =>
    el.setAttribute("aria-label", translate(english)),
  );
  document.title = translate(englishTitle);
  description.content = translate(englishDescription);
  languageButton.setAttribute(
    "aria-label",
    currentLanguage === "mr" ? "Switch to English" : "मराठीत वाचा",
  );
  languageButton.setAttribute("aria-pressed", String(currentLanguage === "mr"));
  languageButton
    .querySelector('[lang="en"]')
    .classList.toggle("selected", currentLanguage === "en");
  languageButton
    .querySelector('[lang="mr"]')
    .classList.toggle("selected", currentLanguage === "mr");
  updateMenuLabel();
  updateEventsLabel();
  document.dispatchEvent(new Event("languagechange"));
  try {
    localStorage.setItem("aatmiyata-language", currentLanguage);
  } catch {
    /* Language switching also works when storage is unavailable. */
  }
}
languageButton.addEventListener("click", () =>
  setLanguage(currentLanguage === "en" ? "mr" : "en"),
);
let savedLanguage = "en";
try {
  savedLanguage = localStorage.getItem("aatmiyata-language") || "en";
} catch {}
setLanguage(savedLanguage);
